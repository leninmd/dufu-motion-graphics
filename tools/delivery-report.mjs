#!/usr/bin/env node
/**
 * Build the final delivery manifest with sizes, SHA-256 hashes and MP4 probe
 * information. Run after encode + contact sheet + QA.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { ROOT } from './server.mjs';

const outDir = path.join(ROOT, 'output', 'v6_pelican_paradigm');
const files = [
  'dufu_test_1080p.mp4',
  'dufu_test_1080p_share.mp4',
  'dufu_test_720p_preview.mp4',
  'contact_sheet_18_eras.png',
].map((f) => path.join(outDir, f)).filter((f) => fs.existsSync(f));

function sha(file) {
  const h = crypto.createHash('sha256');
  const fd = fs.openSync(file, 'r');
  const buf = Buffer.allocUnsafe(1024 * 1024);
  let n;
  while ((n = fs.readSync(fd, buf, 0, buf.length, null)) > 0) h.update(buf.subarray(0, n));
  fs.closeSync(fd);
  return h.digest('hex');
}

const ffmpeg = path.join(ROOT, 'tools', process.platform === 'win32' ? 'ffmpeg.exe' : 'ffmpeg');
function probe(file) {
  if (!file.endsWith('.mp4')) return null;
  const r = spawnSync(ffmpeg, ['-hide_banner', '-i', file], { encoding: 'utf8' });
  const s = (r.stderr || '') + (r.stdout || '');
  const dur = /Duration: ([0-9:.]+)/.exec(s);
  const vline = /Video: ([^\n]+)/.exec(s);
  const aline = /Audio: ([^\n]+)/.exec(s);
  let video = null;
  if (vline) {
    const line = vline[1];
    const size = /(\d{3,4}x\d{3,4})/.exec(line);
    const fps = /([0-9.]+) fps/.exec(line);
    const codec = /^([^,(]+)/.exec(line);
    video = { codec: (codec?.[1] || '').trim(), size: size?.[1] || '', fps: fps ? +fps[1] : null };
  }
  let audio = null;
  if (aline) {
    const line = aline[1];
    const rate = /(\d+) Hz/.exec(line);
    const codec = /^([^,(]+)/.exec(line);
    audio = { codec: (codec?.[1] || '').trim(), sampleRate: rate ? +rate[1] : null };
  }
  return { duration: dur ? dur[1] : null, video, audio };
}

const rows = files.map((f) => {
  const st = fs.statSync(f);
  return {
    file: path.basename(f),
    mb: +(st.size / 1048576).toFixed(2),
    sha256: sha(f),
    probe: probe(f),
  };
});

let qa = null;
try { qa = JSON.parse(fs.readFileSync(path.join(ROOT, 'output', 'v6_qa', 'qa_report.json'), 'utf8')); } catch {}
let audio = null;
try { audio = JSON.parse(fs.readFileSync(path.join(ROOT, 'output', 'audio', 'mix_v6.analysis.json'), 'utf8')); } catch {}

const md = `# 少陵测试 · Delivery Manifest

Generated by \`tools/delivery-report.mjs\`.

| file | size | sha256 | probe |
|---|---:|---|---|
${rows.map((r) => `| \`${r.file}\` | ${r.mb} MB | \`${r.sha256.slice(0, 24)}…\` | ${r.probe ? `${r.probe.duration} · ${r.probe.video?.size || ''} @ ${r.probe.video?.fps || ''} fps · ${r.probe.audio?.codec || ''}` : 'image'} |`).join('\n')}

## SHA-256

${rows.map((r) => `- \`${r.file.replace(/\`/g, '')}\`  \`${r.sha256}\``).join('\n')}

## Film

- 138.0 s · 8,280 frames · 60 fps · 1,920 × 1,080 · 120 BPM · 69 bars.
- 18 eras + 5 × 4 history wall with the empty 19th seat.
- Deterministic Canvas 2D, no external imagery, no recorded voice, no external music.
- All audio generated by Web Audio OfflineAudioContext.

## QA

${qa ? `QA status: **${qa.errors?.length ? 'FAIL' : 'PASS'}** · ${qa.errors?.length || 0} errors · ${qa.warnings?.length || 0} warnings · ${qa.stats?.elapsedSeconds || '?'} s.  
QA report: \`output/v6_qa/qa_report.json\`.` : 'QA report not found.'}

${audio ? `Audio: peak ${audio.analysis?.peakDb ?? audio.peakDb} dBFS · RMS ${audio.analysis?.rmsDb ?? audio.rmsDb} dBFS · ${audio.duration || 138} s · ${audio.sampleRate || 48000} Hz.` : ''}

## Preview

\`node tools/server.mjs 5180\` → <http://127.0.0.1:5180/preview/>
`;

fs.writeFileSync(path.join(outDir, 'DELIVERY.md'), md, 'utf8');
console.log(`wrote ${path.relative(ROOT, path.join(outDir, 'DELIVERY.md'))}`);
for (const r of rows) console.log(`${r.file}  ${r.mb} MB  ${r.probe?.duration || ''}`);
